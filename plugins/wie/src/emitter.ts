/**
 * Output Emitter — writes the complete template ecosystem to disk
 * as a set of JSON manifest files and a folder architecture.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import type { TemplateManifest, FolderArchitecture } from "./types.js";

export function emitOutput(
  manifest: TemplateManifest,
  folderArchitecture: FolderArchitecture,
  opts: { outputDir: string; log?: (e: Record<string, unknown>) => void },
): string[] {
  const { outputDir, log = () => {} } = opts;
  const files: string[] = [];

  const write = (relPath: string, data: unknown): void => {
    const fullPath = join(outputDir, relPath);
    mkdirSync(dirname(fullPath), { recursive: true });
    writeFileSync(fullPath, JSON.stringify(data, null, 2), "utf-8");
    files.push(relPath);
  };

  // ── Main manifest ─────────────────────────────────────────────────
  write("manifest.json", manifest);

  // ── Section library ───────────────────────────────────────────────
  write("sections.json", manifest.sectionLibrary);

  // ── Component library ─────────────────────────────────────────────
  write("components.json", manifest.componentLibrary);

  // ── Motion library ────────────────────────────────────────────────
  write("motions.json", {
    presets: manifest.animationLibrary,
    motionDNA: manifest.motionDNA,
  });

  // ── Page inventory ────────────────────────────────────────────────
  write("pages.json", {
    pageDNA: manifest.pageDNA,
    siteGraph: manifest.siteGraph,
  });

  // ── Design tokens ─────────────────────────────────────────────────
  write("tokens.json", manifest.designTokens);

  // ── Placeholder catalog ───────────────────────────────────────────
  write("placeholders.json", manifest.placeholderCatalog);

  // ── Compatibility graph ───────────────────────────────────────────
  write("compatibility.json", manifest.compatibilityGraph);

  // ── Media schemas ─────────────────────────────────────────────────
  write("media.json", manifest.mediaSchemas);

  // ── CMS schemas ───────────────────────────────────────────────────
  write("cms.json", manifest.cmsSchema);

  // ── Experience timeline ───────────────────────────────────────────
  write("timeline.json", manifest.experienceTimeline);

  // ── Accessibility report ──────────────────────────────────────────
  write("accessibility.json", manifest.accessibilityReport);

  // ── Performance report ────────────────────────────────────────────
  write("performance.json", manifest.performanceReport);

  // ── SEO report ────────────────────────────────────────────────────
  write("seo.json", manifest.seoReport);

  // ── Benchmark scores ──────────────────────────────────────────────
  write("benchmark.json", manifest.benchmark);

  // ── Site graph ────────────────────────────────────────────────────
  write("site-graph.json", manifest.siteGraph);

  // ── Builder specification ─────────────────────────────────────────
  write("builder-spec.json", manifest.builderSpec);

  // ── Themes ────────────────────────────────────────────────────────
  write("themes.json", manifest.themes);

  // ── Pattern recognition ───────────────────────────────────────────
  write("patterns.json", manifest.patternRecognition);

  // ── QA report ─────────────────────────────────────────────────────
  write("qa.json", manifest.qaReport);

  // ── Folder architecture ───────────────────────────────────────────
  write("folder-architecture.json", folderArchitecture);

  // ── Executive summary (human-readable) ────────────────────────────
  write("executive-summary.md", buildExecutiveSummary(manifest, folderArchitecture));

  log({ phase: "emit", files: files.length });
  return files;
}

