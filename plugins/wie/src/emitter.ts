function flattenFolder(nodes: FolderArchitecture["structure"], indent: string): string[] {
  const out: string[] = [];
  for (const node of nodes) {
    const icon = node.type === "directory" ? "+" : "-";
    out.push(`${indent}${icon} ${node.name}`);
    if (node.children) {
      out.push(...flattenFolder(node.children, indent + "  "));
    }
  }
  return out;
}
